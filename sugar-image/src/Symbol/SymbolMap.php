namespace SugarCraft\Image\Symbol;

/**
 * Coverage-class symbol engine — the glyph corpus and candidate search
 * behind the 'symbols' render tier (A-04).
 *
 * SYMBOL-TIER W11: the chafa narrow tables ascii (95), misc-narrow (23)
 * and the orphaned ascii-ibm (95) alternate face are all carried verbatim
 * in {@see SymbolSetTables}; ascii and misc-narrow ride the corpus and the
 * tag grammar (their own tags plus technical/geometric/dot and the nine
 * AMBIGUOUS BAD-vetoes) with no extra opt-in — fully live. ascii-ibm can
 * only be a face swap, never a selector class (chafa declares no IBM tag
 * and its codepoints collide with the ascii table), so it rides through
 * {@see withAsciiIbm()}.
 *
 * Corpus build order mirrors chafa's init_symbol_array_narrow() exactly:
 * the 127 non-wide entries of the basic block-elements/box-drawing table
 * (U+2500–U+259F), then the 256 braille dots (U+2800–U+28FF), the 59
 * teletext sextants (U+1FB00–U+1FB3A, bitmap values skip the two holes
 * 21 and 42 of the 2x3 mosaic block), and the octant set decoded via
 * chafa's 26-entry octant_map with the block-duplicate skip window
 * (only U+1CD00–U+1D000 codepoints are kept; U+2580-range octant
 * spellings are already covered by the basic table).
 *
 * PC-13: chafa's candidate search is a FLAT walk of packed 64-bit
 * bitmaps comparing popcount Hamming distance — NOT a hash lookup —
 * and the per-pixel coverage a symbol paints is BINARY 0/1 read out of
 * that bitmap. The 8-bit 0..255 coverage ramp exists only in the
 * pre-threshold stage: the runtime conversion thresholds it at cov > 127
 * (chafa/chafa-symbol-map.c:240), while the corpus generators pack a
 * truthy coverage.
 * findCandidates() reproduces chafa's insertion-sorted 8-slot buffer
 * statement-for-statement, tie order included: equal distances keep the
 * earlier-scanned symbol first, and the inverse pass (hd' = 64-hd) is
 * gated against the tail slot exactly like the direct pass.
 *
 * PC-14 (fixed-palette quantize-before-scoring) lives in
 * {@see CanvasMode}; the work-factor top-K clamp lives in the renderer
 * that consumes this map.
 *
 * Mirrors chafa.ChafaSymbolMap (chafa/chafa-symbol-map.c, chafa/internal/chafa-symbols.c).
 *
 * A-05b note: chafa's fill stipple map (apply_fill) consumes per-cell
 * FILL flags produced upstream by the pre-renderer; sugar-image cells
 * carry no such flags, so the ░▒▓ stipple glyphs ride the corpus as
 * ordinary candidates and the fill-map selection semantics stay a seam.
 *
 * F-17 corpus extension (2026-10-21): the default corpus stays exactly the
 * 676 W6 entries above — byte-frozen, because {@see SymbolMapRenderer}'s
 * output digest is pinned. Two additive tiers ride the FULL corpus
 * (1,260 glyphs = chafa's narrow symbol array: 95 ASCII + 365 Latin +
 * 229 block-table + 23 misc-narrow + 256 braille + 59 sextant + 234
 * octants, less the U+00B7 duplicate chafa's codepoint-keyed hash
 * collapses) reachable through {@see withSelectors()}, chafa's
 * `--symbols=` tag grammar:
 *  - the U+1FB80–U+1FB8B eighth-block tier generated by
 *    {@see eighthBlockCoverage()} (12 glyphs: upper 1/4, 3/8, 5/8, 3/4,
 *    7/8 and right 1/4, 3/8, 5/8, 3/4, 7/8, plus the upper+lower and
 *    horizontal 1/8 composites) — the coverage classes the U+2500–259F
 *    table has no spelling for;
 *  - the remaining chafa narrow tables carried verbatim by
 *    {@see SymbolSetTables} (ASCII, Latin, misc-narrow, legacy block).
 * chafa-symbols-kana.h is 16x8-outline-only, so the kana set contributes
 * NOTHING to the narrow array — it is chafa's wide symbols2 tier (16x8,
 * two 8x8 halves scored as hd[0]+hd[1]), carried by {@see SymbolSetKana}
 * and partitioned into {@see self::$wideDefs} exactly like chafa's
 * init_symbol_array_wide() keeps the two arrays separate.
 *
 * The opt-in LATIN tier ({@see withLatin()}) is a SEPARATE additive path
 * (SYMBOL-LATIN, W10): chafa's 365 narrow chafa-symbols-latin.h glyphs
 * (U+00A1–U+03F6, table {@see SymbolSetLatin}) appended AFTER the current
 * corpus, so the default 676-entry prefix — and every byte-frozen render
 * digest — stays untouched. It coexists with {@see withSelectors()}, which
 * reaches the same glyphs at their chafa build-order positions through the
 * `latin` tag class; the two paths keep their own transcriptions.
 *
 * Selection mirrors chafa's chafa_symbol_map_apply_selectors() /
 * char_is_selected(): selectors apply in order and the LAST match wins;
 * a token without a leading +/- clears the map first and signs persist
 * across comma-separated tokens; `all` is ~(EXTRA|BAD); a glyph's
 * effective tags are its declared tags OR the default tags derived from
 * its codepoint (chafa's def_to_symbol, AMBIGUOUS masked off); BAD is
 * auto-excluded unless a selector names it. The `[chars]` literal-set and
 * codepoint-range selector forms are NOT implemented (documented seam —
 * sugar-image has no font probe, so tag classes are the useful subset).
 *
 * A-09 (implemented): wide glyphs ride as {@see WideSymbolDef} sym[2]
 * pairs — one 16x8-pixel cell split into two 8x8 halves, scored jointly
 * as hd[0] + hd[1] (inverse against 128). The symbol renderer trials
 * wide-vs-narrow with a lookback pass over each row
 * ({@see SymbolMapRenderer::applyWidePass()} — chafa's N_BUF_CELLS=4 ring
 * is a memory optimization this port has no use for; it materializes
 * whole rows) and replaces the pair on a strictly lower summed error.
 * The double-width emission bookkeeping resolved to a skip at the
 * emission call itself: a committed continuation carries a null glyph
 * and the renderer never feeds it to OutputOptimizer, mirroring the
 * printer's `if (cell->c == 0) continue;` byte-for-byte — no optimizer
 * change was needed because both halves share one pen pair. The C's
 * "add a space when a transparent cell precedes a continuation" idiom
 * lives on the fg-only pass only; this port's transparency discipline
 * never wide-commits over a transparent half, so it is unreachable here
 * (recorded deviation in applyWidePass).
 */
