    /**
     * Apply chafa's `--symbols=` tag selector grammar over the FULL corpus —
     * the narrow array (1,260 unique glyphs) and the wide symbols2 array
     * (181 kana glyphs) — returning a new map holding each selection in its
     * corpus build order.
     *
     * Grammar (chafa_symbol_map_apply_selectors): classes are separated by
     * `+`, `-` or `,`; a class without a sign clears the selection first
     * and signs persist across comma-separated tokens; the LAST matching
     * selector decides a glyph. `all` is every tag except EXTRA and BAD,
     * `none` selects nothing, and BAD (AMBIGUOUS|UGLY) is auto-excluded
     * unless a selector names it — so `all` selects 1,251 of the 1,260-entry
     * narrow array, the nine misc-narrow emoji-variant glyphs staying out
     * exactly as in chafa, plus the 181 WIDE-tagged kana glyphs into the
     * wide selection. A string that BEGINS with `+`/`-` is
     * relative to this map's current corpus, otherwise it replaces it.
     * Unknown class names throw (fail fast, never a silent empty corpus).
     *
     * Seam: chafa's `[chars]` literal sets and codepoint ranges are not
     * implemented — tag classes are the useful subset for this port.
     * Class names must also be complete: chafa's parse_symbol_tag
     * (chafa-symbol-map.c:846-902) accepts any PREFIX of a table name,
     * first-match-wins in table order (`brai` → braille, `al` → all);
     * this port requires the exact name — a documented grammar narrowing,
     * fail-fast over silent near-misses.
     *
     * @throws \InvalidArgumentException on an unknown class or syntax error
     */
    public function withSelectors(string $selectors): self
    {
        $rules = self::parseSelectors($selectors);
        if ($rules === []) {
            throw new \InvalidArgumentException('empty symbol selector expression');
        }

        $relative = preg_match('/^\s*[+-]/', $selectors) === 1;
        $base = [];
        if ($relative) {
            foreach ($this->defs as $def) {
                $base[mb_ord($def->char)] = true;
            }
        }

        $autoExclude = SymbolTags::BAD;
        foreach ($rules as [$mask]) {
            $autoExclude &= ~$mask;
        }

        $baseWide = [];
        if ($relative) {
            foreach ($this->wideDefs as $def) {
                $baseWide[mb_ord($def->char)] = true;
            }
        }

        $select = static function (int $tags, bool $selected) use ($rules, $autoExclude): bool {
            foreach ($rules as [$mask, $add]) {
                if (($tags & $mask) !== 0) {
                    $selected = $add;
                }
            }

            return ($tags & $autoExclude) !== 0 ? false : $selected;
        };

        $picked = [];
        foreach (self::fullCorpus($this->asciiIbm) as $def) {
            $cp = mb_ord($def->char);
            if ($select($def->tags | self::defaultTagsFor($cp), $base[$cp] ?? false)) {
                $picked[] = $def;
            }
        }

        // chafa rebuilds the wide symbols2 array through the same selector
        // walk (apply_selectors feeds both init_symbol_array_* passes), so
        // the tag grammar reaches kana exactly the way it reaches narrow
        // tiers; with no wide glyph inside the selection the result is the
        // byte-frozen narrow-only map.
        $pickedWide = [];
        foreach (self::fullWideCorpus() as $def) {
            $cp = mb_ord($def->char);
            if ($select($def->tags | self::defaultTagsFor($cp), $baseWide[$cp] ?? false)) {
                $pickedWide[] = $def;
            }
        }

        return new self($picked, asciiIbm: $this->asciiIbm, wideDefs: $pickedWide);
    }

    /**
     * @return list<array{0:int, 1:bool}> [tag mask, additive] in source order
     */
    private static function parseSelectors(string $selectors): array
    {
        $rules = [];
        $mode = null;
        $length = strlen($selectors);

        for ($i = 0; $i < $length;) {
            $char = $selectors[$i];

            if ($char === ' ' || $char === ',' || $char === "\t") {
                $i++;
                continue;
            }

            if ($char === '+' || $char === '-') {
                $mode = $char === '+';
                $i++;
                continue;
            }

            if (preg_match('/\G[A-Za-z0-9.]+/', $selectors, $match, 0, $i) !== 1) {
                throw new \InvalidArgumentException('syntax error in symbol selectors at offset ' . $i);
            }

            $mask = SymbolTags::selectorMask(strtolower($match[0]));
            if ($mask === null) {
                throw new \InvalidArgumentException('unknown symbol class "' . $match[0] . '"');
            }

            $rules[] = [$mask, $mode ?? true];
            $mode ??= true;
            $i += strlen($match[0]);
        }

        return $rules;
    }

    /**
     * chafa's get_default_tags_for_char(): WIDE for the wide-capable block
     * this port carries (g_unichar_iswide over U+3041-U+30FE; NARROW is
     * derived only when the glyph is not wide, exactly like chafa). Chafa's
     * AMBIGUOUS wide-cjk envelope stays underived — the corpus carries no
     * glyph inside it, and every AMBIGUOUS the selection sees is declared
     * by its table. def_to_symbol() ORs these into a glyph's declared
     * tags and masks AMBIGUOUS off, so selectors see the C build's
     * effective tags.
     */
    private static function defaultTagsFor(int $cp): int
    {
        $tags = self::isWideCodepoint($cp) ? SymbolTags::WIDE : SymbolTags::NARROW;

        if ($cp <= 0x7F) {
            $tags |= SymbolTags::ASCII;
        } elseif ($cp >= 0x2300 && $cp <= 0x23FF) {
            $tags |= SymbolTags::TECHNICAL;
        } elseif ($cp >= 0x25A0 && $cp <= 0x25FF) {
            $tags |= SymbolTags::GEOMETRIC;
        } elseif ($cp >= 0x2800 && $cp <= 0x28FF) {
            $tags |= SymbolTags::BRAILLE;
        } elseif ($cp >= 0x1FB00 && $cp <= 0x1FB3B) {
            $tags |= SymbolTags::SEXTANT;
        }

        $char = mb_chr($cp, 'UTF-8');
        if ($char !== false && preg_match('/^\p{L}$/u', $char) === 1) {
            $tags |= SymbolTags::ALPHA;
        }
        if ($char !== false && preg_match('/^\p{Nd}$/u', $char) === 1) {
            $tags |= SymbolTags::DIGIT;
        }

        return $tags;
    }

    /**
     * The wide-capable envelope g_unichar_iswide answers true for inside
     * the corpus this port carries: today the kana block chafa compiles
     * into symbols2. A future wide tier extending the wide array extends
     * this ladder (and it, not the AMBIGUOUS wide-cjk envelope chafa also
     * derives, is what tags the glyphs here).
     */
    private static function isWideCodepoint(int $cp): bool
    {
        return $cp >= 0x3041 && $cp <= 0x30FF;
    }

    /**
     * chafa's find_candidates(): a flat popcount-Hamming walk of every
     * corpus bitmap maintaining an insertion-sorted window of the eight
     * best (symbol, inverted) trials. Equal distances keep scan order;
     * an inverse trial (64 - hd) rides the same buffer.
     *
     * @return list<array{0:SymbolDef, 1:bool}> sorted ascending by distance
     */
    public function findCandidates(int $bitmap, bool $allowInverse, int $limit): array
    {
        // 8 slots seeded {index 0, hd 65, inverted false} exactly as chafa does.
        $cand = array_fill(0, 8, [0, 65, false]);

        foreach ($this->defs as $i => $def) {
            $hd = self::popcount($bitmap ^ $def->bits);
            if ($hd < $cand[7][1]) {
                self::insertCandidate($cand, [$i, $hd, false]);
            }
            if ($allowInverse) {
                $hd = 64 - $hd;
                if ($hd < $cand[7][1]) {
                    self::insertCandidate($cand, [$i, $hd, true]);
                }
            }
        }

        $valid = 0;
        foreach ($cand as $slot) {
            if ($slot[1] > 64) {
                break;
            }
            $valid++;
        }

        if ($limit < 1) {
            throw new \InvalidArgumentException('candidate limit must be >= 1, got ' . $limit);
        }

        $out = [];
        $n = min($valid, $limit);
        for ($k = 0; $k < $n; $k++) {
            $out[] = [$this->defs[$cand[$k][0]], $cand[$k][2]];
        }

        return $out;
    }

    /**
     * A-09: chafa's find_wide_candidates (chafa-symbol-map.c:1268) — the
     * same 8-slot insertion buffer over the WIDE selection, but the
     * distance is the joint hamming of the two 8x8 halves against the
     * candidate's sym[0]/sym[1] pair, seeded at hd 129 with the inverse
     * trial at 128 - hd. The scan order is chafa's own:
     * compare_symbols2_popcount sorts symbols2 ascending by joint weight
     * then codepoint (stable across equal keys), not build order — the
     * wide array is sorted at init in the C, and this port keeps that
     * law so ties resolve exactly like chafa's.
     *
     * An empty wide selection yields the empty list, which is the
     * structural byte-freeze door: the renderer's wide pass can never
     * commit over a narrow pair when no wide candidate exists.
     *
     * @return list<array{0:WideSymbolDef, 1:bool}> sorted ascending by joint distance
     *
     * @throws \InvalidArgumentException on a limit below 1
     */
    public function findWideCandidates(int $bitmapLeft, int $bitmapRight, bool $allowInverse, int $limit): array
    {
        if ($limit < 1) {
            throw new \InvalidArgumentException('candidate limit must be >= 1, got ' . $limit);
        }

        // chafa sorts symbols2 once at init; memoized per map instance.
        $sorted = $this->wideCorpus();
        if ($sorted === []) {
            return [];
        }

        $cand = array_fill(0, 8, [0, 129, false]);

        foreach ($sorted as $i => $def) {
            $hd = self::popcount($bitmapLeft ^ $def->bitsLeft) + self::popcount($bitmapRight ^ $def->bitsRight);
            if ($hd < $cand[7][1]) {
                self::insertCandidate($cand, [$i, $hd, false]);
            }
            if ($allowInverse) {
                $hd = 128 - $hd;
                if ($hd < $cand[7][1]) {
                    self::insertCandidate($cand, [$i, $hd, true]);
                }
            }
        }

        $valid = 0;
        foreach ($cand as $slot) {
            if ($slot[1] > 128) {
                break;
            }
            $valid++;
        }

        $out = [];
        $n = min($valid, $limit);
        for ($k = 0; $k < $n; $k++) {
            $out[] = [$sorted[$cand[$k][0]], $cand[$k][2]];
        }

        return $out;
    }

    /**
     * chafa coverage_to_bitmap(): row-major MSB-first packing of the
     * 8x8 coverage, pixel (x,y) landing on bit 63-(y*8+x). Two faces:
     * the corpus generators (outline 255/0, braille/sextant/octant
     * 1/0) use the truthy form exactly like chafa's internal one; the
     * runtime conversion of a 0..255 pixel ramp passes $threshold = 127
     * (chafa/chafa-symbol-map.c:240) — the single place the 8-bit ramp
     * becomes binary (PC-13).
     *
     * @param list<int> $coverage 64 bytes, 0..255 each
     */
    public static function coverageToBitmap(array $coverage, ?int $threshold = null): int
    {
        if (count($coverage) !== 64) {
            throw new \InvalidArgumentException('symbol coverage must hold exactly 64 pixels, got ' . count($coverage));
        }

        $bitmap = 0;
        foreach ($coverage as $cov) {
            $on = $threshold === null ? $cov !== 0 : $cov > $threshold;
            $bitmap = ($bitmap << 1) | ($on ? 1 : 0);
        }

        return $bitmap;
    }

    /**
     * chafa bitmap_to_bytes(): the binary coverage bytes painted by a
     * bitmap, index = y*8+x (the same bit order as coverageToBitmap).
     *
     * @return list<int> 64 bytes, each 0 or 1
     */
    public static function coverageOf(int $bitmap): array
    {
        $cov = [];
        for ($i = 0; $i < 64; $i++) {
            $cov[] = ($bitmap >> (63 - $i)) & 1;
        }

        return $cov;
    }

    /**
     * @param array{0:int, 1:int, 2:bool} $entry
     * @param array{0:int, 1:int, 2:bool} $cand
     */
    private static function insertCandidate(array &$cand, array $entry): void
    {
        // Walk from slot 6 down; the first slot whose distance is <= the
        // new distance places the new entry right after it (stable ties),
        // otherwise it lands at 0. Tail slot 7 is shadow work — chafa's
        // insertion point never exceeds it because the gate tested < cand[7].
        for ($i = 6; $i >= 0; $i--) {
            if ($entry[1] >= $cand[$i][1]) {
                for ($j = 7; $j > $i + 1; $j--) {
                    $cand[$j] = $cand[$j - 1];
                }
                $cand[$i + 1] = $entry;

                return;
            }
        }

        for ($j = 7; $j > 0; $j--) {
            $cand[$j] = $cand[$j - 1];
        }
        $cand[0] = $entry;
    }

    private static function popcount(int $x): int
    {
        // Sign bit handled by test-then-mask: x & (x-1) at PHP_INT_MIN
        // overflows to float and wedges the Kernighan loop.
        $n = ($x >> 63) & 1;
        $x &= PHP_INT_MAX;
        while ($x !== 0) {
            $x &= $x - 1;
            $n++;
        }

        return $n;
    }

    /**
     * @return list<int>
     */
    private static function outlineToCoverage(string $outline): array
    {
        $cov = [];
        foreach (explode('|', $outline) as $row) {
            for ($u = 0; $u < 8; $u++) {
                $cov[] = $row[$u] === 'X' ? 255 : 0;
            }
        }

        return $cov;
    }

    /** gen_braille_sym: dots 1-3 left col bands, 4-6 right col bands, 7-8 fourth band. */
    private static function brailleCoverage(int $val): array
    {
        $cov = array_fill(0, 64, 0);

        $left = $val & 1;
        $right = ($val >> 3) & 1;
        $cov[1] = $cov[2] = $left;
        $cov[5] = $cov[6] = $right;

        $left = ($val >> 1) & 1;
        $right = ($val >> 4) & 1;
        $cov[17] = $cov[18] = $left;
        $cov[21] = $cov[22] = $right;

        $left = ($val >> 2) & 1;
        $right = ($val >> 5) & 1;
        $cov[33] = $cov[34] = $left;
        $cov[37] = $cov[38] = $right;

        $left = ($val >> 6) & 1;
        $right = ($val >> 7) & 1;
        $cov[49] = $cov[50] = $left;
        $cov[53] = $cov[54] = $right;

        return $cov;
    }

    /** gen_sextant_sym: 3x2 grid, bit y*2+x; each sextant paints 3 px rows x 4 px cols, middle row shared. */
    private static function sextantCoverage(int $val): array
    {
        $cov = array_fill(0, 64, 0);
        for ($y = 0; $y < 3; $y++) {
            for ($x = 0; $x < 2; $x++) {
                if (!($val & (1 << ($y * 2 + $x)))) {
                    continue;
                }
                for ($v = 0; $v < 3; $v++) {
                    $row = $y * 3 + $v;
                    if ($row > 3) {
                        $row--;
                    }
                    for ($u = 0; $u < 4; $u++) {
                        $cov[$row * 8 + $x * 4 + $u] = 1;
                    }
                }
            }
        }

        return $cov;
    }

    /**
     * The U+1FB80–U+1FB8B eighth-block coverage, derived from the glyph's
     * Unicode name: 'upper' fills the first n of eight rows, 'right' the
     * last n of eight columns, 'both' the first and last row, and
     * 'stripes' rows 1, 3, 5 and 8 (U+1FB81's HORIZONTAL ONE EIGHTH
     * BLOCK-1358). 8x8 pixels means one row per eighth vertically and one
     * column per eighth horizontally.
     *
     * @return list<int> 64 bytes, 0 or 1
     */
    private static function eighthBlockCoverage(string $axis, int $eighths): array
    {
        if ($eighths < 1 || $eighths > 7) {
            throw new \InvalidArgumentException('eighth-block fill must be 1..7 eighths, got ' . $eighths);
        }

        $cov = array_fill(0, 64, 0);

        switch ($axis) {
            case 'upper':
                for ($y = 0; $y < $eighths; $y++) {
                    for ($x = 0; $x < 8; $x++) {
                        $cov[$y * 8 + $x] = 1;
                    }
                }
                break;
            case 'right':
                for ($y = 0; $y < 8; $y++) {
                    for ($x = 8 - $eighths; $x < 8; $x++) {
                        $cov[$y * 8 + $x] = 1;
                    }
                }
                break;
            case 'both':
                for ($x = 0; $x < 8; $x++) {
                    $cov[$x] = 1;
                    $cov[56 + $x] = 1;
                }
                break;
            case 'stripes':
                foreach ([0, 2, 4, 7] as $y) {
                    for ($x = 0; $x < 8; $x++) {
                        $cov[$y * 8 + $x] = 1;
                    }
                }
                break;
            default:
                throw new \InvalidArgumentException('unknown eighth-block axis "' . $axis . '"');
        }

        return $cov;
    }

    /** find_unicode_octant_map_data: binary search; miss yields -(insertion point). */    private static function findOctantData(int $bits): int
    {
        $map = self::OCTANT_MAP;
        $first = 0;
        $last = count($map);
        while ($first < $last) {
            $mid = intdiv($first + $last, 2);
            if ($map[$mid][0] < $bits) {
                $first = $mid + 1;
            } elseif ($map[$mid][0] > $bits) {
                $last = $mid;
            } else {
                return $map[$mid][1];
            }
        }

        return -$first;
    }

    /** octant_bits_to_unichar, verbatim decode including the skip-window-relevant shapes. */
    private static function octantBitsToUnichar(int $bits): int
    {
        $data = self::findOctantData($bits);

        if ($data < 0) {
            return (($bits + $data) & 0xFFFFFFFF) | 0x1CD00;
        }

        if ($data === 0x00) {
            return 0x00A0;
        }

        return match (($data >> 5) & 0x3) {
            0 => ($data & 0x1F) | 0x2580,
            1 => ($data & 0x1F) | 0x1CEA0,
            2 => ($data & 0x1F) | 0x1FB80,
            default => ($data & 0x1F) | 0x1FBE6,
        };
    }

    /** octant_bits_to_coverage: 4 bands of 2 px rows x 2 cols of 4 px; bit (y&~1)+((x>>2)&1). */
    private static function octantBitsToCoverage(int $bits): array
    {
        $cov = [];
        for ($y = 0; $y < 8; $y++) {
            for ($x = 0; $x < 8; $x++) {
                $bit = ($y & ~1) + (($x >> 2) & 1);
                $cov[] = ($bits >> $bit) & 1;
            }
        }

        return $cov;
    }

    /**
     * Informational tags for the basic table (v1 does not filter on tags);
     * transcribed from chafa's own per-glyph tag lists in
     * chafa/internal/chafa-symbols-block.h (v1 does not filter on tags).
     */
    private static function basicTags(int $cp): int
    {
        // Block glyph family 0x2580-0x259F: chafa's exact per-codepoint tags.
        if ($cp >= 0x2580 && $cp <= 0x259F) {
            return match (true) {
                $cp === 0x2580 => SymbolTags::BLOCK | SymbolTags::VHALF | SymbolTags::QUAD | SymbolTags::OCTANT | SymbolTags::INVERTED,
                $cp === 0x2584 => SymbolTags::BLOCK | SymbolTags::VHALF | SymbolTags::QUAD | SymbolTags::OCTANT,
                $cp === 0x2582 || $cp === 0x2586 => SymbolTags::BLOCK | SymbolTags::OCTANT,
                $cp === 0x2588 => SymbolTags::BLOCK | SymbolTags::SOLID | SymbolTags::QUAD | SymbolTags::SEXTANT | SymbolTags::OCTANT,
                $cp === 0x258C => SymbolTags::BLOCK | SymbolTags::HHALF | SymbolTags::QUAD | SymbolTags::SEXTANT | SymbolTags::OCTANT,
                $cp === 0x2590 => SymbolTags::BLOCK | SymbolTags::HHALF | SymbolTags::QUAD | SymbolTags::SEXTANT | SymbolTags::OCTANT | SymbolTags::INVERTED,
                $cp >= 0x2591 && $cp <= 0x2593 => SymbolTags::STIPPLE,
                $cp === 0x2594 || $cp === 0x2595 => SymbolTags::BLOCK | SymbolTags::INVERTED,
                \in_array($cp, [0x2596, 0x2597, 0x2598, 0x259A, 0x259D], true) => SymbolTags::BLOCK | SymbolTags::QUAD | SymbolTags::OCTANT,
                \in_array($cp, [0x2599, 0x259B, 0x259C, 0x259E, 0x259F], true) => SymbolTags::BLOCK | SymbolTags::QUAD | SymbolTags::OCTANT | SymbolTags::INVERTED,
                default => SymbolTags::BLOCK,
            };
        }

        if (\in_array($cp, [0x2504, 0x2505, 0x2506, 0x2507, 0x2508, 0x2509, 0x250A, 0x250B,
            0x254C, 0x254D, 0x254E, 0x254F, 0x2574, 0x2575, 0x2576, 0x2577, 0x2578, 0x2579,
            0x257A, 0x257B], true)) {
            return SymbolTags::BORDER | SymbolTags::DOT;
        }

        if ($cp >= 0x2571 && $cp <= 0x2573) {
            return SymbolTags::BORDER | SymbolTags::DIAGONAL;
        }

        return SymbolTags::BORDER;
    }

    private static function chr(int $codepoint): string
    {
        $char = mb_chr($codepoint, 'UTF-8');
        if ($char === false) {
            throw new \InvalidArgumentException('invalid codepoint ' . $codepoint);
        }

        return $char;
    }
