    /**
     * Opt-in LATIN tier: chafa's 365 narrow chafa-symbols-latin.h glyphs
     * (U+00A1-U+03F6, table {@see SymbolSetLatin}) appended after the
     * current corpus.
     *
     * chafa's own model — the default symbol map selects only the BLOCK,
     * BORDER and SPACE tags (chafa/chafa-canvas-config.c:73-75), so latin
     * and friends are reached through the --symbols tag selectors, never
     * the default. Appending last keeps candidate tie order stable and
     * leaves the default corpus — and every byte-frozen render digest —
     * untouched. Idempotent: a map that already carries the tier returns
     * itself, and on a map whose SELECTION already holds the tier's
     * codepoints (chafa's `all` reaches latin through the tag grammar) the
     * append adds only the still-missing ones, so composing it after
     * withSelectors() can never duplicate a codepoint. This mirrors
     * chafa's rebuild_symbols() hash keyed by codepoint — the same
     * uniqueness law {@see self::fullCorpus()} enforces for the U+00B7
     * cross-table collision — and the in-place walk of
     * {@see self::withAsciiIbm()}: an already-carried slot keeps its
     * selected spelling; the tier never re-spells it.
     *
     * Flag law (F-17, unchanged): withSelectors() results reset the
     * latin flag; the flag records withLatin()-built provenance, while
     * codepoint presence — not the flag — is what makes an append a no-op.
     */
    public function withLatin(): self
    {
        if ($this->latin) {
            return $this;
        }

        $present = self::codepointKeys($this->defs);
        $extra = [];
        foreach (SymbolSetLatin::OUTLINES as $cp => $outline) {
            if (isset($present[$cp])) {
                continue;
            }
            $extra[] = self::outlineDef($cp, $outline, SymbolTags::LATIN);
        }

        return new self([...$this->defs, ...$extra], true, $this->asciiIbm);
    }

    /** Whether the opt-in LATIN tier is appended (see {@see withLatin()}). */
    public function hasLatin(): bool
    {
        return $this->latin;
    }

    /**
     * Swap the ascii tier (U+0020–U+007E) to chafa's orphaned IBM face —
     * the verbatim chafa-symbols-ascii-ibm.h transcription in
     * {@see SymbolSetTables::ASCII_IBM}.
     *
     * chafa never wires that header (symbol_defs[] includes only
     * ascii/latin/block/kana/misc-narrow — see the table docblock), and
     * because codepoints collide 1:1 the ascii data can only be a FACE
     * SWAP, never a selector class; the ASCII/ALPHA/DIGIT/SPACE tags it
     * declares keep the tier reachable through every selector the regular
     * ascii face answers to. Codepoints the map does not carry are
     * untouched, so on the default corpus (no ascii glyphs) this is a
     * no-op flag; a later withSelectors() re-derives the corpus from
     * {@see self::fullCorpus()} and selects the face-swapped glyphs.
     * Idempotent; unlike the latin seam above, the flag SURVIVES
     * withSelectors() — the face is not an appended tier, so preserving
     * it cannot double-apply.
     */
    public function withAsciiIbm(): self
    {
        if ($this->asciiIbm) {
            return $this;
        }

        $table = SymbolSetTables::asciiIbm();
        $defs = [];
        foreach ($this->defs as $def) {
            $cp = mb_ord($def->char);
            if (isset($table[$cp])) {
                [$outline, $declared] = $table[$cp];
                $defs[] = self::outlineDef($cp, $outline, $declared);
            } else {
                $defs[] = $def;
            }
        }

        return new self($defs, $this->latin, true);
    }

    /** Whether the ascii tier carries the IBM face (see {@see withAsciiIbm()}). */
    public function hasAsciiIbm(): bool
    {
        return $this->asciiIbm;
    }

    /**
     * Opt-in KANA wide tier: chafa's 181 16x8 chafa-symbols-kana.h glyphs
     * (U+3041-U+30FE, table {@see SymbolSetKana}) appended after the
     * current wide selection as chafa's wide symbols2 pairs
     * ({@see WideSymbolDef}) — never the narrow corpus.
     *
     * chafa's init_symbol_array_wide() takes exactly these glyphs (outline
     * length 128 and a wide codepoint) into symbols2 while
     * init_symbol_array_narrow() skips them, so a kana glyph can only ever
     * be picked by the A-09 wide machinery, and only when a selection
     * carries wide glyphs at all: with zero wide defs the wide pass is
     * structurally inert (chafa's update_cells_wide early-returns on
     * n_symbols2 == 0), which is the byte-freeze door for every existing
     * digest. Idempotent; like {@see withLatin()} the flag is carried by
     * withKana()-built maps only and a withSelectors() result rebuilds the
     * wide selection from the tag grammar instead. Also like withLatin(),
     * the append filters codepoints the wide selection already carries
     * (chafa's rebuild_symbols codepoint-hash uniqueness), so composing
     * it after a wide-carrying selection — `all` includes WIDE — adds
     * nothing and can never duplicate a glyph.
     */
    public function withKana(): self
    {
        if ($this->kana) {
            return $this;
        }

        $present = self::codepointKeys($this->wideDefs);
        $extra = [];
        foreach (self::fullWideCorpus() as $def) {
            if (isset($present[mb_ord($def->char)])) {
                continue;
            }
            $extra[] = $def;
        }

        return new self($this->defs, $this->latin, $this->asciiIbm, [...$this->wideDefs, ...$extra], true);
    }

    /** Whether the opt-in KANA wide tier is appended (see {@see withKana()}). */
    public function hasKana(): bool
    {
        return $this->kana;
    }

    /**
     * The map's wide (two-cell) selection in build order — chafa's
     * symbols2 array. Empty on every narrow-only map, so the A-09 render
     * pass never activates for the default corpus or the latin/ascii-ibm
     * tiers.
     *
     * @return list<WideSymbolDef>
     */
    public function wideDefs(): array
    {
        return $this->wideDefs;
    }

    /**
     * A-09: the wide selection in chafa's symbols2 scan order — joint
     * popcount ascending, ties by codepoint ascending
     * ({@see findWideCandidates()} narrows inside the same order; the
     * renderer's exhaustive path walks it directly, so ties resolve
     * exactly like the C's init-sorted array).
     *
     * @return list<WideSymbolDef>
     */
    public function wideCorpus(): array
    {
        if ($this->sortedWideDefs === null) {
            $sorted = $this->wideDefs;
            usort(
                $sorted,
                static fn (WideSymbolDef $a, WideSymbolDef $b): int
                    => $a->weight !== $b->weight
                        ? $a->weight <=> $b->weight
                        : mb_ord($a->char) <=> mb_ord($b->char),
            );
            $this->sortedWideDefs = $sorted;
        }

        return $this->sortedWideDefs;
    }

    /**
     * chafa's wide symbols2 array as built from symbol_defs[]: today the
     * kana table only — the single 16x8 tier chafa compiles in. Declared
     * tags are CHAFA_SYMBOL_TAG_NONE; selection sees the effective tags
     * from {@see defaultTagsFor()} (WIDE | ALPHA), exactly like chafa's
     * def_to_symbol.
     *
     * @return list<WideSymbolDef>
     */
    private static function fullWideCorpus(): array
    {
        $defs = [];
        foreach (SymbolSetKana::OUTLINES as $cp => $outline) {
            $defs[] = WideSymbolDef::fromOutline16x8(self::chr($cp), $outline, 0);
        }

        return $defs;
    }

    /**
     * The default corpus: chafa's block table (U+2500–259F), the braille
     * dots, the sextants and the octants — byte-frozen since W6.
     *
     * @return list<SymbolDef>
     */
    private static function defaultCorpus(): array
    {
        $defs = [];
        foreach (self::BASIC as $cp => $outline) {
            $defs[] = self::outlineDef($cp, $outline, self::basicTags($cp));
        }

        return [...$defs, ...self::generatedTiers()];
    }

    /**
     * chafa's full narrow symbol array (1,260 unique glyphs) in
     * symbol_defs build order:
     * ASCII, Latin, block table, misc-narrow, then the generated braille,
     * sextant and octant tiers. The kana table contributes nothing (16x8
     * outlines only — see the class docblock).
     *
     * @param bool $asciiIbm swap the ascii table for chafa's orphaned IBM
     *                       face ({@see withAsciiIbm()}); positions, count
     *                       and every other table are untouched, so the
     *                       1,260-entry shape and the U+00B7 collapse law
     *                       hold for either face.
     *
     * @return list<SymbolDef>
     */
    private static function fullCorpus(bool $asciiIbm = false): array
    {
        $defs = [];

        foreach ($asciiIbm ? SymbolSetTables::asciiIbm() : SymbolSetTables::ascii() as $cp => [$outline, $declared]) {
            $defs[] = self::outlineDef($cp, $outline, $declared);
        }
        foreach (SymbolSetTables::latin() as $cp => [$outline, $declared]) {
            $defs[] = self::outlineDef($cp, $outline, $declared);
        }
        foreach (self::BASIC as $cp => $outline) {
            $defs[] = self::outlineDef($cp, $outline, self::basicTags($cp));
        }
        foreach (SymbolSetTables::legacyBlock() as $cp => [$outline, $declared]) {
            $defs[] = self::outlineDef($cp, $outline, $declared);
        }
        foreach (self::EIGHTH_BLOCKS as $cp => [$axis, $eighths, $tags]) {
            $defs[] = SymbolDef::new(
                self::chr($cp),
                self::coverageToBitmap(self::eighthBlockCoverage($axis, $eighths)),
                $tags,
            );
        }
        foreach (SymbolSetTables::misc() as $cp => [$outline, $declared]) {
            $defs[] = self::outlineDef($cp, $outline, $declared);
        }

        // chafa's rebuild_symbols() keys a hash by codepoint, so the ONE
        // codepoint two tables spell differently (U+00B7: latin.h's 1-pixel
        // dot vs misc-narrow.h's 2-pixel DOT) collapses to the later table's
        // glyph in the earlier table's position — 1,260 unique narrow glyphs.
        $byCp = [];
        foreach ([...$defs, ...self::generatedTiers()] as $def) {
            $byCp[mb_ord($def->char)] = $def;
        }

        return array_values($byCp);
    }

    /**
     * @return list<SymbolDef>
     */
    private static function generatedTiers(): array
    {
        $defs = [];

        for ($cp = 0x2800; $cp < 0x2900; $cp++) {
            $defs[] = SymbolDef::new(
                self::chr($cp),
                self::coverageToBitmap(self::brailleCoverage($cp - 0x2800)),
                SymbolTags::BRAILLE,
            );
        }

        for ($cp = 0x1FB00; $cp < 0x1FB3B; $cp++) {
            $val = $cp - 0x1FB00 + 1;
            if ($val > 20) {
                $val++;
            }
            if ($val > 41) {
                $val++;
            }
            $defs[] = SymbolDef::new(
                self::chr($cp),
                self::coverageToBitmap(self::sextantCoverage($val)),
                SymbolTags::LEGACY | SymbolTags::SEXTANT,
            );
        }

        for ($oct = 0; $oct < 256; $oct++) {
            $cp = self::octantBitsToUnichar($oct);
            // Skip block symbols; the basic table already owns those.
            if ($cp < 0x1CD00 || $cp > 0x1D000) {
                continue;
            }
            $defs[] = SymbolDef::new(
                self::chr($cp),
                self::coverageToBitmap(self::octantBitsToCoverage($oct)),
                SymbolTags::LEGACY | SymbolTags::OCTANT,
            );
        }

        return $defs;
    }

    private static function outlineDef(int $cp, string $outline, int $tags): SymbolDef
    {
        return SymbolDef::new(
            self::chr($cp),
            self::coverageToBitmap(self::outlineToCoverage($outline)),
            $tags,
        );
    }

    /**
     * The codepoint set of a def list as presence keys — chafa's
