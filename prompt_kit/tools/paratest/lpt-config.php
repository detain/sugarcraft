<?php

declare(strict_types=1);

/*
 * Generate a phpunit config whose single <testsuite> lists every test file
 * longest-first, so ParaTest 7.4.9's one-file-at-a-time queue becomes LPT
 * scheduling (it dispatches <file> entries in listed order; verified).
 *
 * usage: php lpt-config.php <lib-dir> <durations.(xml|tsv)> <out.xml> [--bootstrap=<abs path>]
 *   durations: a junit from any phpunit/paratest run of this lib (per-file time =
 *              sum of its testcase times) or a TSV "path<TAB>seconds" (the
 *              scripts/parallel-tests-durations.tsv shape, repo-root-relative).
 *   Every file the base config's <testsuite> directories select is emitted;
 *   files with no recorded duration go FIRST (unknown = assume slow), so a
 *   stale durations file can only cost balance, never drop a test.
 */

[$self, $lib, $durations, $out] = array_pad($argv, 4, null);
if ($out === null) {
    fwrite(STDERR, "usage: php $self <lib-dir> <durations.(xml|tsv)> <out.xml> [--bootstrap=<abs path>]\n");
    exit(2);
}
$lib = rtrim((string) realpath($lib), '/');
$base = "$lib/phpunit.xml";
$bootstrapOverride = null;
foreach (array_slice($argv, 4) as $arg) {
    if (str_starts_with($arg, '--bootstrap=')) {
        $bootstrapOverride = substr($arg, 12);
    }
}
require "$lib/vendor/autoload.php";

$abs = static fn (string $p): string => str_starts_with($p, '/') ? $p : "$lib/$p";

// 1. durations, keyed by absolute path
$dur = [];
if (str_ends_with($durations, '.xml')) {
    $x = simplexml_load_file($durations) ?: throw new RuntimeException("cannot read $durations");
    foreach ($x->xpath('//testcase[@file]') as $tc) {
        $dur[(string) $tc['file']] = ($dur[(string) $tc['file']] ?? 0.0) + (float) $tc['time'];
    }
} else {
    $repo = dirname($lib);
    foreach (file($durations, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) as $line) {
        [$path, $secs] = explode("\t", $line) + [1 => '0'];
        $dur[str_starts_with($path, '/') ? $path : "$repo/$path"] = (float) $secs;
    }
}

// 2. the file set the base config selects (same iterator PHPUnit uses)
$dom = new DOMDocument();
$dom->preserveWhiteSpace = false;
$dom->load($base);
$xp = new DOMXPath($dom);
$files = [];
foreach ($xp->query('/phpunit/testsuites/testsuite') as $suite) {
    $exclude = [];
    foreach ($xp->query('exclude', $suite) as $e) {
        $exclude[] = $abs(trim($e->textContent));
    }
    foreach ($xp->query('directory', $suite) as $d) {
        $suffix = $d->getAttribute('suffix') ?: 'Test.php';
        array_push($files, ...(new SebastianBergmann\FileIterator\Facade())->getFilesAsArray($abs(trim($d->textContent)), $suffix, '', $exclude));
    }
    foreach ($xp->query('file', $suite) as $f) {
        $files[] = (string) realpath($abs(trim($f->textContent)));
    }
}
$files = array_values(array_unique($files));
$unknown = array_values(array_filter($files, static fn ($f) => !isset($dur[$f])));
$known = array_values(array_filter($files, static fn ($f) => isset($dur[$f])));
usort($known, static fn ($a, $b) => $dur[$b] <=> $dur[$a] ?: strcmp($a, $b));
$ordered = array_merge($unknown, $known);

// 3. rewrite the base config: absolute paths, one LPT-ordered testsuite
$root = $dom->documentElement;
foreach (['bootstrap', 'cacheDirectory', 'cacheResultFile'] as $attr) {
    if ($root->hasAttribute($attr)) {
        $root->setAttribute($attr, $abs($root->getAttribute($attr)));
    }
}
if ($bootstrapOverride !== null) {
    $root->setAttribute('bootstrap', $bootstrapOverride);
}
$root->removeAttribute('xsi:noNamespaceSchemaLocation');
foreach ($xp->query('/phpunit/source//directory | /phpunit/source//file | /phpunit/coverage//directory | /phpunit/coverage//file') as $n) {
    $n->textContent = $abs(trim($n->textContent));
}
$old = $xp->query('/phpunit/testsuites')->item(0);
$new = $dom->createElement('testsuites');
$suite = $dom->createElement('testsuite');
$suite->setAttribute('name', 'lpt');
foreach ($ordered as $f) {
    $suite->appendChild($dom->createElement('file', htmlspecialchars($f, ENT_XML1)));
}
$new->appendChild($suite);
$root->replaceChild($new, $old);
$root->insertBefore($dom->createComment(sprintf(
    ' GENERATED by prompt_kit/tools/paratest/lpt-config.php from %s + %s: %d files, %d without a recorded duration (placed first) ',
    $base,
    $durations,
    count($ordered),
    count($unknown),
)), $new);
$dom->formatOutput = true;
$dom->save($out);
fprintf(STDERR, "wrote %s: %d files (%d unknown-duration first), top: %s (%.1fs)\n", $out, count($ordered), count($unknown), $known ? basename($known[0]) : '-', $known ? $dur[$known[0]] : 0);
