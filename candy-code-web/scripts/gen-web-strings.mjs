#!/usr/bin/env node
// Generates src-web/lib/strings.en.generated.ts from candy-code's committed
// chrome bundle (candy-code/docs/protocol/web-strings.en.json, itself
// generated from candy-code/lang/en.php by
// candy-code/scripts/gen-web-strings.php and re-derived in CI by
// tests/Protocol/WebStringsDriftTest).
//
//   npm run gen:strings            rewrite strings.en.generated.ts
//   npm run gen:strings -- --check exit 1 when the mirror is stale
//
// STRINGS_PATH overrides where the bundle is read from; the default is the
// monorepo sibling. A split-repo clone has no sibling, and needs none: the
// mirror is committed, so building the UI never runs this (same law as
// gen-protocol.mjs). The output is deterministic: bundle order, no dates.
//
// C-TUI-6.f (owner ruling): the bundle carries chrome/UI strings ONLY —
// server, tool and model text stay untranslated and never reach this file.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const bundlePath = resolve(process.env.STRINGS_PATH ?? resolve(root, '../candy-code/docs/protocol/web-strings.en.json'))
const outPath = resolve(root, 'src-web/lib/strings.en.generated.ts')
const check = process.argv.includes('--check')

let bundle
try {
  bundle = JSON.parse(readFileSync(bundlePath, 'utf8'))
} catch (e) {
  console.error(`web strings: cannot read the bundle: ${e.message}`)
  process.exit(2)
}
if (bundle === null || typeof bundle !== 'object' || Array.isArray(bundle)) {
  console.error('web strings: the bundle is not an object')
  process.exit(2)
}
for (const [key, value] of Object.entries(bundle)) {
  if (typeof value !== 'string') {
    console.error(`web strings: ${key} is not a string`)
    process.exit(2)
  }
  if (!key.startsWith('web.')) {
    console.error(`web strings: ${key} is outside the chrome prefix (ruling: web. keys only)`)
    process.exit(2)
  }
}

const header = `// Generated by scripts/gen-web-strings.mjs from candy-code's
// docs/protocol/web-strings.en.json — the web UI chrome strings in the base
// language, byte-identical to what \`server.strings\` answers with no locale
// (or no server at all). Do not edit; run \`npm run gen:strings\` instead.

`
const out = `${header}export const WEB_STRINGS_EN: Record<string, string> = ${JSON.stringify(bundle, null, 4)};
`

if (check) {
  let current = null
  try {
    current = readFileSync(outPath, 'utf8')
  } catch {
    current = null
  }
  if (current !== out) {
    console.error("web strings: src-web/lib/strings.en.generated.ts is stale — run 'npm run gen:strings' in candy-code-web/ and commit it")
    process.exit(1)
  }
  process.exit(0)
}

writeFileSync(outPath, out)
console.log(`web strings: wrote src-web/lib/strings.en.generated.ts (${Object.keys(bundle).length} keys)`)
