    /**
     * Full reflective census of one class, deterministic ordering.
     *
     * @param class-string $class
     */
    private static function census(string $class): string
    {
        $rc = new ReflectionClass($class);
        $out = [];
        $consts = [];
        foreach ($rc->getReflectionConstants() as $k) {
            $vis = $k->isPublic() ? 'public' : ($k->isProtected() ? 'protected' : 'private');
            $consts[] = sprintf('%s %s = %s', $vis, $k->getName(), json_encode($k->getValue()));
        }
        sort($consts);
        $out[] = 'CONSTANTS ' . count($consts);
        foreach ($consts as $c) {
            $out[] = '  ' . $c;
        }
        $methods = [];
        foreach ($rc->getMethods() as $rm) {
            if ($rm->getDeclaringClass()->getName() !== $class) {
                continue;
            }
            $vis = $rm->isPublic() ? 'public' : ($rm->isProtected() ? 'protected' : 'private');
            $methods[$rm->getName()] = sprintf(
                '  %s%s %s%s %s',
                $vis,
                $rm->isStatic() ? ' static' : '',
                $rm->getName(),
                self::signature($rm),
                $rm->isPublic() ? 'public' : 'hidden'
            );
        }
        ksort($methods);
        $out[] = 'METHODS ' . count($methods);
        foreach ($methods as $m) {
            $out[] = $m;
        }
        $public = [];
        foreach ($rc->getMethods(ReflectionMethod::IS_PUBLIC) as $rm) {
            $public[] = $rm->getName() . self::signature($rm);
        }
        sort($public);
        $out[] = 'PUBLIC_SIGNATURES ' . count($public);
        foreach ($public as $p) {
            $out[] = '  ' . $p;
        }

        return implode("\n", $out) . "\n";
    }

    private static function signature(ReflectionMethod $rm): string
    {
        $parts = [];
        foreach ($rm->getParameters() as $p) {
            $t = $p->getType();
            $parts[] = ($t === null ? '' : ((string) $t) . ' ')
                . ($p->isVariadic() ? '...' : '')
                . '$' . $p->getName()
                . ($p->isDefaultValueAvailable() && !$p->isVariadic() ? ' = ' . json_encode($p->getDefaultValue()) : '');
        }
        $rt = $rm->getReturnType();

        return '(' . implode(', ', $parts) . ')' . ($rt === null ? '' : ': ' . ((string) $rt));
    }
