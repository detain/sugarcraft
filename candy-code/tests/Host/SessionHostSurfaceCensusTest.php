/**
 * CWPD-14 guard: a structural census of the two files the SessionHost/Serve
 * split moves code between, pinned BEFORE any move (OD-30 guard-first law).
 *
 * The law: the split is MOVE-ONLY. Reflection compiles trait methods into the
 * composing class, so before==after the class must answer with the identical
 * inventory - every constant (name, visibility, value), every method (name,
 * visibility, staticness, parameter list with defaults, return type). If a
 * split lands and this census drifts in ANY direction, the move was not a
 * move - it edited, dropped, renamed or re-typed something, and the weld must
 * not proceed.
 *
 * This test adds no behavior contract; the behavior lock is
 * {@see ChatParityCitationTest} (re-anchored by this lane to follow the prose
 * into the composition files) plus the tests/Server, tests/Host and
 * tests/Protocol suites.
 */
final class SessionHostSurfaceCensusTest extends TestCase
