    /**
     * A method whose shape exercises every branch of
     * {@see self::signature()}: required type, nullable type with null
     * default, typed variadic, return type. Pinned so a census rewrite that
     * silently drops a component reddens here instead of vacuously agreeing
     * with itself.
     */
    public static function probeCarryingEverything(string $req, ?array $opt = null, int ...$rest): ?string
    {
        return $req;
    }

    /**
     * @return array<string, array{0: class-string}>
     */
    public static function censusSubjects(): array
    {
        return [
            'Serve' => [Serve::class],
            'SessionHost' => [SessionHost::class],
        ];
    }

    /**
     * The golden was generated by reflection at base 45bc09526 BEFORE the
     * CWPD-14 split and is embedded byte-verbatim. Regenerating it is
     * deliberate malpractice.
     *
     * A split that COPIES instead of MOVES cannot hide: PHP lets a class
     * method shadow a same-named trait method silently, so the body count
     * across the composition unit is pinned too - one `function <name>(`
     * per censused method, before and after.
     */
    #[DataProvider('censusSubjects')]
    public function testTheStructuralCensusIsByteIdenticalToThePreSplitGolden(string $class): void
    {
        $goldens = self::goldens();
        self::assertArrayHasKey($class, $goldens, 'census subject list drifted');
        $goldenLines = explode("\n", rtrim($goldens[$class], "\n"));
        $actualLines = explode("\n", rtrim(self::census($class), "\n"));
        $delta = [];
        foreach (array_diff($goldenLines, $actualLines) as $line) {
            $delta[] = '- ' . $line;
        }
        foreach (array_diff($actualLines, $goldenLines) as $line) {
            $delta[] = '+ ' . $line;
            if (count($delta) >= 20) {
                break;
            }
        }
        self::assertSame(
            $goldenLines,
            $actualLines,
            'structural census drift for ' . $class . ' (delta: ' . implode(' | ', $delta) . ')'
        );
    }

    #[DataProvider('censusSubjects')]
    public function testEveryMethodHasExactlyOneBodyAcrossTheUnit(string $class): void
    {
        $rc = new ReflectionClass($class);
        $files = [(string) $rc->getFileName()];
        $companion = dirname($files[0]) . '/' . $rc->getShortName();
        if (is_dir($companion)) {
            foreach (scandir($companion) as $entry) {
                if (str_ends_with($entry, '.php')) {
                    $files[] = $companion . '/' . $entry;
                }
            }
        }
        $haystack = '';
        foreach ($files as $file) {
            $haystack .= (string) file_get_contents($file);
        }
        foreach ($rc->getMethods() as $rm) {
            if ($rm->getDeclaringClass()->getName() !== $class) {
                continue;
            }
            self::assertSame(
                1,
                substr_count($haystack, 'function ' . $rm->getName() . '('),
                'method body count drifted for ' . $rm->getName() . ' across the ' . $rc->getShortName() . ' unit'
            );
        }
    }

    /**
     * Vacuity pair: the census derivation must be able to fail. The probe
     * method above carries every signature component; losing any of them
     * from the derivation drops this assertion.
     */
    public function testTheCensusDerivationIsNotVacuous(): void
    {
        $lines = explode("\n", self::census(self::class));
        $probeLine = null;
        foreach ($lines as $line) {
            if (str_starts_with(trim($line), 'public static probeCarryingEverything')) {
                $probeLine = $line;
            }
        }
        self::assertIsString($probeLine, 'census() lost the probe method entirely');
        self::assertStringContainsString('string $req, ?array $opt = null, int ...$rest): ?string', $probeLine);
    }

